"""Turn run records into a results table, and audit the datasets for provenance problems."""

import json
from pathlib import Path

import numpy as np
from scipy.stats import ks_2samp

from cancer_detection.data import FEATURE_COLUMNS, LABEL_COLUMN, SPLIT_FILES, TASKS, fingerprint, load_split
from cancer_detection.evaluation import ppv_at_prevalence
from cancer_detection.experiment import SCREENING_PREVALENCE


def load_records(runs_dir):
    return [json.loads(p.read_text()) for p in sorted(Path(runs_dir).glob("*.json"))]


def always_cancer_f1(n_cancer, n_healthy):
    prevalence = n_cancer / (n_cancer + n_healthy)
    return 2 * prevalence / (1 + prevalence)


def ppv_range(test):
    """PPV at screening prevalence across the specificity interval; 41 healthy samples make it very uncertain."""
    low, high = (ppv_at_prevalence(test["sensitivity"], spec, SCREENING_PREVALENCE) for spec in test["specificity_ci"])
    return f"{test['ppv_at_screening_prevalence']:.3f} [{low:.3f}, {high:.3f}]"


def interval(values):
    return f"[{values[0]:.2f}, {values[1]:.2f}]"


def task_table(records):
    """Rows sorted by nested-CV balanced accuracy, which is the only score used to pick a model."""
    records = sorted(records, key=lambda r: r["nested_cv"]["balanced_accuracy"]["mean"], reverse=True)
    lines = ["| Experiment | CV balanced acc | CV ROC-AUC | Test balanced acc | Test ROC-AUC [95% CI] | "
             "Sensitivity [95% CI] | Specificity [95% CI] | Sens. @95% spec. | PPV @1% prevalence [range] |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in records:
        cv, t = r["nested_cv"], r["test"]
        lines.append(
            f"| {r['spec']['name']} | {cv['balanced_accuracy']['mean']:.3f} ± {cv['balanced_accuracy']['std']:.3f} "
            f"| {cv['roc_auc']['mean']:.3f} ± {cv['roc_auc']['std']:.3f} | {t['balanced_accuracy']:.3f} "
            f"| {t['roc_auc']:.3f} {interval(t['roc_auc_ci'])} "
            f"| {t['sensitivity']:.2f} {interval(t['sensitivity_ci'])} "
            f"| {t['specificity']:.2f} {interval(t['specificity_ci'])} | {t['sensitivity_at_95_specificity']:.2f} "
            f"| {ppv_range(t)} |")
    return "\n".join(lines)


def summary_markdown(records):
    sections = ["# Results", "",
                "Generated by `python -m cancer_detection summary` from `results/runs/*.json`. Within each task, "
                "rows are ordered by nested cross-validation balanced accuracy, the only score used to choose a "
                "model; the held-out test columns are reported for transparency and were never used for selection.",
                "", "Balanced accuracy of 0.5 is chance. Sensitivity = cancers caught; specificity = healthy people "
                "correctly cleared. PPV @1% prevalence is the share of positive calls that would be real cancers "
                "in a screening population where 1% have cancer; the range applies the specificity interval, "
                "so a perfect 41/41 specificity does not read as a perfect PPV."]
    for task in TASKS.values():
        task_records = [r for r in records if r["spec"]["task"] == task.name]
        if not task_records:
            continue
        size = task_records[0]["test_size"]
        sections += ["", f"## {task.name}: {task.description}", "",
                     f"Test set: {size['cancer']} cancer, {size['healthy']} healthy. Always predicting cancer "
                     f"gives balanced accuracy 0.500 and cancer-class F1 "
                     f"{always_cancer_f1(size['cancer'], size['healthy']):.3f}.", "", task_table(task_records)]
    return "\n".join(sections) + "\n"


def audit_markdown(data_dir):
    """Checks that can be run on the data alone; provenance questions that cannot are listed explicitly."""
    train, test = load_split("train", data_dir), load_split("test", data_dir)
    lines = ["# Data audit", "", "Generated by `python -m cancer_detection audit`.", "", "## Files", ""]
    lines += [f"- `{name}`: {len(frame)} rows, SHA-256 `{fingerprint(Path(data_dir) / name)}`"
              for frame, name in ((train, SPLIT_FILES["train"]), (test, SPLIT_FILES["test"]))]
    lines += ["", "## Class counts", "", "| Class | Train | Test |", "|---|---|---|"]
    for label in train[LABEL_COLUMN].value_counts().index:
        lines.append(f"| {label} | {(train[LABEL_COLUMN] == label).sum()} | {(test[LABEL_COLUMN] == label).sum()} |")
    shared = len(train[FEATURE_COLUMNS].merge(test[FEATURE_COLUMNS], how="inner"))
    lines += ["", "## Integrity", "", "- Schema, value range (0, 1], row max-normalisation, labels: passed",
              "- Duplicate rows within each split: none", f"- Identical rows shared by train and test: {shared}"]
    lines += ["", "## Train/test distribution shift", "",
              "Two-sample Kolmogorov-Smirnov test per fragment length, within each class. A length counts as "
              "shifted when p < 0.05 / 350 (Bonferroni). The effect size is the median absolute standardised mean "
              "difference (SMD) across lengths; below about 0.2 is conventionally small.", "",
              "| Class | Train / test samples | Shifted lengths (of 350) | Median abs. SMD |", "|---|---|---|---|"]
    for label in train[LABEL_COLUMN].value_counts().index:
        a = train.loc[train[LABEL_COLUMN] == label, FEATURE_COLUMNS]
        b = test.loc[test[LABEL_COLUMN] == label, FEATURE_COLUMNS]
        p_values = np.array([ks_2samp(a[c], b[c]).pvalue for c in FEATURE_COLUMNS])
        smd = np.median(np.abs((a.mean() - b.mean()) / np.sqrt((a.var() + b.var()) / 2)))
        lines.append(f"| {label} | {len(a)} / {len(b)} | {int((p_values < 0.05 / len(FEATURE_COLUMNS)).sum())} "
                     f"| {smd:.2f} |")
    lines += ["", "Effect sizes are small and similar for every class. Larger classes show more 'shifted' lengths "
              "because the test has more power; subsampled to the healthy class's size (60 / 41), no class shows "
              "a significant shift. So the healthy class is not shift-free, only too small to detect it."]
    lines += ["", "## Open provenance questions", "",
              "These cannot be answered from the files and must be checked with whoever produced the data:", "",
              "- Were healthy and cancer samples collected at the same sites and sequenced in the same batches?",
              "- Do the groups differ in age or sex? Cancer patients are usually older, and age changes cfDNA.",
              "- Can one patient appear more than once (for example, repeat draws) across train and test?",
              "- How was the train/test split made (random, by site, by time)?"]
    return "\n".join(lines) + "\n"
