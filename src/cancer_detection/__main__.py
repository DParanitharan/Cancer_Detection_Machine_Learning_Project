"""Command line: python -m cancer_detection {run,summary,audit,analysis} ..."""

import argparse
import json
import logging
from pathlib import Path

from cancer_detection.analysis import importance_section, learning_curve_section
from cancer_detection.data import DEFAULT_DATA_DIR
from cancer_detection.experiment import load_config, run
from cancer_detection.reporting import audit_markdown, load_records, summary_markdown

PROJECT_ROOT = Path(__file__).resolve().parents[2]
log = logging.getLogger("cancer_detection")


def select(specs, names):
    if not names:
        return specs
    unknown = set(names) - {s.name for s in specs}
    if unknown:
        raise SystemExit(f"unknown experiment names: {sorted(unknown)}")
    return [s for s in specs if s.name in names]


def cmd_run(args):
    specs, cv = load_config(args.config)
    runs_dir = Path(args.runs_dir)
    runs_dir.mkdir(parents=True, exist_ok=True)
    for spec in select(specs, args.only):
        log.info("running %s", spec.name)
        record = run(spec, cv, args.data_dir, args.models_dir if args.save_models else None)
        (runs_dir / f"{spec.name}.json").write_text(json.dumps(record, indent=2))
        cv_ba, test_ba = record["nested_cv"]["balanced_accuracy"]["mean"], record["test"]["balanced_accuracy"]
        log.info("%s: CV balanced acc %.3f | test balanced acc %.3f (%.0fs)", spec.name, cv_ba, test_ba,
                 record["runtime_seconds"])


def cmd_summary(args):
    Path(args.out).write_text(summary_markdown(load_records(args.runs_dir)))
    log.info("wrote %s", args.out)


def cmd_audit(args):
    Path(args.out).write_text(audit_markdown(args.data_dir))
    log.info("wrote %s", args.out)


def cmd_analysis(args):
    specs, cv = load_config(args.config)
    figures_dir = Path(args.out).parent / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    lines = ["# Analysis", "", "Generated by `python -m cancer_detection analysis`. Uses training data only."]
    for spec in select(specs, args.names):
        log.info("analysing %s", spec.name)
        lines += ["", f"## {spec.name}", ""] + learning_curve_section(spec, cv, args.data_dir, figures_dir)
        lines += [""] + importance_section(spec, cv, args.data_dir, figures_dir)
    Path(args.out).write_text("\n".join(lines) + "\n")
    log.info("wrote %s", args.out)


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python -m cancer_detection")
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    commands = parser.add_subparsers(dest="command", required=True)

    run_p = commands.add_parser("run", help="nested CV + one held-out test evaluation per experiment")
    run_p.add_argument("config", type=Path)
    run_p.add_argument("--only", nargs="+", help="experiment names to run (default: all)")
    run_p.add_argument("--runs-dir", default=PROJECT_ROOT / "results" / "runs")
    run_p.add_argument("--save-models", action="store_true")
    run_p.add_argument("--models-dir", default=PROJECT_ROOT / "models")
    run_p.set_defaults(func=cmd_run)

    summary_p = commands.add_parser("summary", help="write the results table from run records")
    summary_p.add_argument("--runs-dir", default=PROJECT_ROOT / "results" / "runs")
    summary_p.add_argument("--out", default=PROJECT_ROOT / "reports" / "results.md")
    summary_p.set_defaults(func=cmd_summary)

    audit_p = commands.add_parser("audit", help="check data integrity and train/test shift")
    audit_p.add_argument("--out", default=PROJECT_ROOT / "reports" / "data_audit.md")
    audit_p.set_defaults(func=cmd_audit)

    analysis_p = commands.add_parser("analysis", help="learning curves and permutation importance")
    analysis_p.add_argument("config", type=Path)
    analysis_p.add_argument("--names", nargs="+", required=True)
    analysis_p.add_argument("--out", default=PROJECT_ROOT / "reports" / "analysis.md")
    analysis_p.set_defaults(func=cmd_analysis)

    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", datefmt="%H:%M:%S")
    args.func(args)


if __name__ == "__main__":
    main()
